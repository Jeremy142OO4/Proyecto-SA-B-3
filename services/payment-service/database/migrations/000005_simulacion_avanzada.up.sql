CREATE TABLE IF NOT EXISTS configuracion_simulacion_pagos (
 id BOOLEAN PRIMARY KEY DEFAULT TRUE CHECK(id),
 habilitada BOOLEAN NOT NULL DEFAULT FALSE,
 tasa_fallos DOUBLE PRECISION NOT NULL DEFAULT 0 CHECK(tasa_fallos BETWEEN 0 AND 100),
 latencia_ms INTEGER NOT NULL DEFAULT 0 CHECK(latencia_ms BETWEEN 0 AND 30000),
 timeout_ms INTEGER NOT NULL DEFAULT 1000 CHECK(timeout_ms BETWEEN 1 AND 30000),
 forzar_timeout BOOLEAN NOT NULL DEFAULT FALSE,
 version BIGINT NOT NULL DEFAULT 0,
 id_administrador UUID,
 actualizada_en TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp()
);
INSERT INTO configuracion_simulacion_pagos(id) VALUES(TRUE) ON CONFLICT DO NOTHING;
CREATE TABLE IF NOT EXISTS simulaciones_pago (
 id_pago UUID PRIMARY KEY REFERENCES pagos(id_pago) ON DELETE CASCADE,
 version_configuracion BIGINT NOT NULL,
 configuracion JSONB NOT NULL,
 resultado VARCHAR(10) NOT NULL CHECK(resultado IN ('EXITO','FALLO','TIMEOUT')),
 espera_ms INTEGER NOT NULL CHECK(espera_ms BETWEEN 0 AND 30000),
 inicio TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
 finalizada_en TIMESTAMPTZ,
 duracion_segundos DOUBLE PRECISION
);
